-- V1__initial_schema.sql
-- Initial schema for Offline UPI Mesh (Accounts and Transactions)

CREATE TABLE accounts (
    vpa VARCHAR(100) PRIMARY KEY,
    holder_name VARCHAR(100) NOT NULL,
    balance NUMERIC(19, 2) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_account_balance_non_negative CHECK (balance >= 0)
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    packet_hash VARCHAR(64) NOT NULL,
    sender_vpa VARCHAR(100) NOT NULL,
    receiver_vpa VARCHAR(100) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    signed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    settled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    bridge_node_id VARCHAR(100) NOT NULL,
    hop_count INT NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT uq_transactions_packet_hash UNIQUE (packet_hash),
    CONSTRAINT fk_transactions_sender FOREIGN KEY (sender_vpa) REFERENCES accounts(vpa),
    CONSTRAINT fk_transactions_receiver FOREIGN KEY (receiver_vpa) REFERENCES accounts(vpa),
    CONSTRAINT chk_transaction_amount_positive CHECK (amount > 0)
);

CREATE INDEX idx_tx_settled_at ON transactions (settled_at DESC);
